import sys, os, re, json, subprocess, datetime

KOREN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def izmeri_rez():
    """Najvišji dejansko izmerjen rez — iz naslovov komitov pri viru ( ⟨ne⟩ iz spomina ⊙ PADC-47 )."""
    try:
        izp = subprocess.run(['git', 'log', '--format=%s', '-200'], cwd=KOREN,
                             capture_output=True, text=True, encoding='utf-8', errors='replace').stdout
    except Exception as e:
        return None, f'× git: {e}'
    naj = -1
    for m in re.finditer(r'rez (\d+)', izp):
        naj = max(naj, int(m.group(1)))
    return naj, None

def kolizija(n):
    """Preveri, da rez ⟨n⟩ še ne živi v naslovih ( varovalka pred pisanjem ⊢ Z-2 ∧ 1542 )."""
    try:
        izp = subprocess.run(['git', 'log', '--format=%s', '--all'], cwd=KOREN,
                             capture_output=True, text=True, encoding='utf-8', errors='replace').stdout
    except Exception as e:
        return False, f'× git: {e}'
    return (f'rez {n} ' in izp) or (f'rez {n}:' in izp), None

